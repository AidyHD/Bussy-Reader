const fs = require('node:fs');
const path = require('node:path');

const packageRoot = path.resolve(__dirname, '..');
const pdfjsPath = path.join(packageRoot, 'node_modules', 'pdfjs-dist', 'legacy', 'build', 'pdf.min.mjs');
const pdfjsWorkerPath = path.join(packageRoot, 'node_modules', 'pdfjs-dist', 'build', 'pdf.worker.min.mjs');
const outputPath = path.join(packageRoot, 'lib', 'pdfjs-source.ts');

if (!fs.existsSync(pdfjsPath)) {
  throw new Error(`PDF.js runtime not found at ${pdfjsPath}`);
}
if (!fs.existsSync(pdfjsWorkerPath)) {
  throw new Error(`PDF.js worker not found at ${pdfjsWorkerPath}`);
}

const source = fs.readFileSync(pdfjsPath, 'utf8');
const workerSource = fs.readFileSync(pdfjsWorkerPath, 'utf8');
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(
  outputPath,
  `// Generated by scripts/generate-pdfjs-source.js. Do not edit by hand.\n` +
    `export const pdfjsSource = ${JSON.stringify(source)};\n` +
    `export const pdfjsWorkerSource = ${JSON.stringify(workerSource)};\n`,
);